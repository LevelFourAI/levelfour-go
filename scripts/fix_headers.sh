#!/usr/bin/env bash
set -euo pipefail

cd "$(dirname "$0")/.."

count=0
while IFS= read -r -d '' file; do
    if head -1 "$file" | grep -q "^// This file was auto-generated by Fern from our API Definition\.$"; then
        if [[ "$OSTYPE" == darwin* ]]; then
            sed -i '' '1s|^// This file was auto-generated by Fern from our API Definition\.$|// Code generated by Fern from our API Definition; DO NOT EDIT.|' "$file"
        else
            sed -i '1s|^// This file was auto-generated by Fern from our API Definition\.$|// Code generated by Fern from our API Definition; DO NOT EDIT.|' "$file"
        fi
        count=$((count + 1))
    fi
done < <(find . -name '*.go' -not -path './examples/*' -not -path './.git/*' -print0)

echo "Fixed $count file headers"

for f in reference.md api.md; do
    if [ -f "$f" ]; then
        rm -f "$f"
        echo "Removed generated $f (canonical reference lives on docs.levelfour.ai)"
    fi
done
